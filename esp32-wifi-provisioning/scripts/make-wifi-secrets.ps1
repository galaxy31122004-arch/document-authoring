<#
  make-wifi-secrets.ps1 - prepare an ESP32 (PlatformIO / Arduino) project for WiFi.
  1. Reads the local credentials file (default D:\Secrets\wifi-credentials.json).
  2. Checks which saved networks the PC can see now. If none is visible, takes the
     network this PC is using (get-pc-wifi logic) and saves it to the credentials file.
  3. Writes <Project>\include\wifi_secrets.h (visible networks first), adds it to .gitignore.
  4. Copies wifi_nvs.h / wifi_nvs.cpp into the project if they are not there yet.
  5. Adds a "WiFi ESP32" section to the nearest AGENTS.md (or creates AGENTS.md + CLAUDE.md
     in the project) so later AI sessions follow this skill. -NoAgentsNote skips it.

  Run:  powershell -ExecutionPolicy Bypass -File make-wifi-secrets.ps1 -Project <folder with platformio.ini>
        [-Allow5GHz] [-NoPcFallback] [-NoTemplate] [-CredentialsPath <file>]
#>
param(
  [Parameter(Mandatory)][string]$Project,
  [string]$CredentialsPath = 'D:\Secrets\wifi-credentials.json',
  [switch]$Allow5GHz, [switch]$NoPcFallback, [switch]$NoTemplate, [switch]$NoAgentsNote
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'wifi-common.ps1')
$Max = 8   # keep in sync with WIFI_NVS_MAX

$Project = (Resolve-Path $Project).Path
if ($Project -like 'D:\TMT\*') { Write-Error 'TMT project: personal skills do not apply here (GLOBAL_RULES).'; exit 1 }
if (-not (Test-Path (Join-Path $Project 'platformio.ini'))) { Write-Warning "No platformio.ini in $Project; continuing anyway." }

$cred = Read-Credentials $CredentialsPath
$visible = Get-VisibleNetworks
$usable = @{}   # ssid -> signal of a band the chip can use
foreach ($v in $visible) {
  $sig = if ($Allow5GHz) { Get-BestSignal $v } else { Get-BestSignal $v -Only24 }
  if ($sig -ge 0) { $usable[$v.Ssid] = $sig }
}

$inRange = @($cred.networks | Where-Object { $usable.ContainsKey($_.ssid) })
if (-not $inRange -and -not $NoPcFallback) {
  Write-Host 'No saved network is in range. Taking the network this PC is using...'
  $pc = Get-PcWifiCandidates -Allow5GHz:$Allow5GHz
  foreach ($c in $pc.Candidates) {
    $st = Set-CredentialEntry $cred $c.Ssid $c.Password 'pc' $c.Band $c.Note
    Write-Host "  $st $($c.Ssid)  ($($c.Note))"
    if ($c.Note -match 'ASSUMED') { Write-Warning "  Password for '$($c.Ssid)' is a guess (same as the 5 GHz band). Fix it with add-wifi.ps1 if it fails." }
  }
  if ($pc.Problem) { Write-Warning $pc.Problem }
  $inRange = @($cred.networks | Where-Object { $usable.ContainsKey($_.ssid) })
}

if (-not $cred.portalPassword) {
  $chars = 'abcdefghjkmnpqrstuvwxyz23456789'.ToCharArray()
  $cred.portalPassword = -join (1..10 | ForEach-Object { $chars | Get-Random })
}
Write-Credentials $cred $CredentialsPath

# Order: networks in range (strongest first), then the others (newest first).
$ordered = @($inRange | Sort-Object { $usable[$_.ssid] } -Descending) +
           @($cred.networks | Where-Object { -not $usable.ContainsKey($_.ssid) } | Sort-Object added -Descending)
if ($ordered.Count -gt $Max) {
  Write-Warning "$($ordered.Count) networks saved; only the first $Max go into the firmware."
  $ordered = $ordered[0..($Max - 1)]
}

function ConvertTo-CString([string]$s) { return '"' + (($s -replace '\\', '\\') -replace '"', '\"') + '"' }

$rows = @($ordered | ForEach-Object { "  {$(ConvertTo-CString $_.ssid), $(ConvertTo-CString $_.password)}," })
$body = ($rows -join "`n") + "`n" + $cred.portalPassword
$sha = [Security.Cryptography.SHA256]::Create().ComputeHash([Text.Encoding]::UTF8.GetBytes($body))
$ver = [BitConverter]::ToUInt32($sha, 0); if ($ver -eq 0) { $ver = 1 }
if (-not $rows) { $rows = @('  {nullptr, nullptr},  // no network: firmware opens the setup portal') }

$header = @"
// wifi_secrets.h - GENERATED by esp32-wifi-provisioning/make-wifi-secrets.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm').
// Contains WiFi passwords. Listed in .gitignore: never commit, never paste into docs or chat.
// Regenerate instead of editing; the firmware copies this list into NVS when VERSION changes.
#pragma once
#include <stddef.h>

#define WIFI_SECRETS_VERSION 0x$('{0:X8}' -f $ver)u
#define WIFI_PORTAL_PASSWORD $(ConvertTo-CString $cred.portalPassword)

struct WifiDefault { const char* ssid; const char* pass; };
static const WifiDefault WIFI_DEFAULTS[] = {
$($rows -join "`n")
};
static const size_t WIFI_DEFAULT_COUNT = $(@($ordered).Count);
"@

$inc = Join-Path $Project 'include'
if (-not (Test-Path $inc)) { New-Item -ItemType Directory $inc | Out-Null }
$hdrPath = Join-Path $inc 'wifi_secrets.h'
[IO.File]::WriteAllText($hdrPath, ($header -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding $false))

# .gitignore next to platformio.ini
$gi = Join-Path $Project '.gitignore'
$line = 'include/wifi_secrets.h'
if (-not ((Test-Path $gi) -and (Select-String -Path $gi -SimpleMatch $line -Quiet))) {
  Add-Content -Path $gi -Value $line -Encoding ascii
  Write-Host "Added '$line' to $gi"
}
$ErrorActionPreference = 'Continue'   # git writes to stderr when the folder is not a repo
$tracked = $null
if (Get-Command git -ErrorAction SilentlyContinue) {
  $tracked = & cmd /c "git -C `"$Project`" ls-files --error-unmatch include/wifi_secrets.h 2>nul"
}
if ($tracked) { Write-Warning 'wifi_secrets.h is ALREADY tracked by git: run  git rm --cached include/wifi_secrets.h  and consider changing the passwords.' }

if (-not $NoTemplate) {
  $tpl = Join-Path $PSScriptRoot '..\templates\arduino'
  foreach ($f in @(@('wifi_nvs.h', 'include'), @('wifi_nvs.cpp', 'src'))) {
    $dst = Join-Path (Join-Path $Project $f[1]) $f[0]
    if (Test-Path $dst) { Write-Host "Kept existing $dst"; continue }
    New-Item -ItemType Directory -Force (Split-Path $dst) | Out-Null
    Copy-Item (Join-Path $tpl $f[0]) $dst
    Write-Host "Copied $dst"
  }
}

# Pointer for future AI sessions: "WiFi ESP32" section in the nearest AGENTS.md (workspace root),
# or a new AGENTS.md + CLAUDE.md in the project when it is not inside a workspace.
if (-not $NoAgentsNote) {
  $agents = $null; $d = Get-Item $Project
  while ($d) {
    $cand = Join-Path $d.FullName 'AGENTS.md'
    if (Test-Path $cand) { $agents = $cand; break }
    $d = $d.Parent
  }
  if (-not $agents) {
    $agents = Join-Path $Project 'AGENTS.md'
    [IO.File]::WriteAllText($agents, "# $(Split-Path $Project -Leaf)`n`n", (New-Object Text.UTF8Encoding $false))
    $claude = Join-Path $Project 'CLAUDE.md'
    if (-not (Test-Path $claude)) { [IO.File]::WriteAllText($claude, "@AGENTS.md`n", (New-Object Text.UTF8Encoding $false)) }
    Write-Host "Created $agents (+ CLAUDE.md pointing to it)"
  }
  $baseDir = Split-Path $agents
  $rel = if ($Project -eq $baseDir) { '.' } else { $Project.Substring($baseDir.Length).TrimStart('\') -replace '\\', '/' }
  $text = [IO.File]::ReadAllText($agents, [Text.Encoding]::UTF8)
  $marker = '<!-- wifi-projects -->'
  if ($text -notmatch '<!-- esp32-wifi-provisioning -->') {
    $section = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '..\templates\agents-wifi-section.md'), [Text.Encoding]::UTF8)
    $section = $section.Replace('{{PROJECTS}}', "``$rel``")
    $text = $text.TrimEnd() + "`n`n" + $section
    [IO.File]::WriteAllText($agents, $text, (New-Object Text.UTF8Encoding $false))
    Write-Host "Added 'WiFi ESP32' section to $agents"
  } elseif ($text.Contains($marker) -and -not $text.Contains("``$rel``")) {
    $text = $text.Replace(" $marker", ", ``$rel`` $marker")
    [IO.File]::WriteAllText($agents, $text, (New-Object Text.UTF8Encoding $false))
    Write-Host "Listed $rel in the 'WiFi ESP32' section of $agents"
  }
}

Write-Host "`nWrote $hdrPath  (version 0x$('{0:X8}' -f $ver))"
$ordered | ForEach-Object {
  [pscustomobject]@{ ssid = $_.ssid; password = (Hide-Password $_.password); inRange = $usable.ContainsKey($_.ssid); signal = $(if ($usable.ContainsKey($_.ssid)) { "$($usable[$_.ssid])%" } else { '' }) }
} | Format-Table -AutoSize | Out-String | Write-Host
if (-not $inRange) { Write-Warning 'No network usable by the ESP32 is in range now. The firmware will open the setup portal if it cannot connect.' }
